// Builds the Photoshop UXP scripts (single files — the execute-actions sandbox
// can only require photoshop / uxp / fs, so our code is bundled in):
//
//   dist/color-detection.psjs            config from additionalContents[0] (per run)
//   dist/color-detection.embedded.psjs   config embedded (test data) — for a node
//                                        that only takes a script
//   dist/color-detection.local-test.psjs desktop Photoshop harness: opens the test
//                                        background, runs, copies the JSON out,
//                                        closes ONLY that document
//   dist/execute-actions.request.json    example Photoshop API v2 request body (not sent)
//
// Production ("Photoshop action V2" node, Workflow Builder):
//   dist/color-decision.psjs             config from Assets → decision as XMP only
//   dist/config.<variant>.png            config PNGs for the Assets port (test-data/config.*.json)
//   dist/color-decision.local-<variant>.psjs  desktop harness (with --background --probe-dir)
//
//   node poc/photoshop-action-v2/build.mjs [--config <json>] [--background <png>] [--out <json>]
import { build } from 'esbuild'
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { makeConfigPng } from './make-config-png.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const DIST = join(HERE, 'dist')
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d }
const configFile = resolve(arg('--config', join(HERE, 'test-data/config.marderabwehr.json')))
const background = arg('--background', '')
const localOut = arg('--out', '')

async function bundle(extraFooter = '', embedded = null, entry = 'src/entry.js') {
  const r = await build({
    entryPoints: [join(HERE, entry)],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: '__colorDetection',
    platform: 'neutral',
    target: 'es2019',
    external: ['photoshop', 'uxp', 'fs'],
    mainFields: ['main'],
    legalComments: 'none',
  })
  let code = r.outputFiles[0].text
  if (embedded !== null) {
    const literal = JSON.stringify('@@EMBEDDED_CONFIG@@')
    if (!code.includes(literal)) throw new Error('embedded-config sentinel lost in bundle')
    code = code.replace(literal, JSON.stringify(JSON.stringify(JSON.parse(embedded))))
  }
  if (!code.includes('__ADDITIONAL_CONTENTS_PATH_0__')) throw new Error('placeholder lost in bundle')
  return `// Territory Color Detection — Photoshop UXP script (PoC). Generated by build.mjs; do not edit.\n${code}\n${extraFooter}`
}

export async function buildAll() {
  mkdirSync(DIST, { recursive: true })
  const config = readFileSync(configFile, 'utf8')
  JSON.parse(config)
  // Photoshop unloads a script when its top-level code returns and drops pending
  // async work (verified in Photoshop 27.10) — so the run is awaited at top level.
  // *.noawait.psjs: Adobe's documented style (bare call) for the cloud comparison.
  const run = 'try { await __colorDetection.run(); } catch (e) { console.error(e); }\n'
  const runNoAwait = 'Promise.resolve(__colorDetection.run()).catch(function (e) { console.error(e) });\n'
  writeFileSync(join(DIST, 'color-detection.psjs'), await bundle(run))
  writeFileSync(join(DIST, 'color-detection.embedded.psjs'), await bundle(run, config))
  if (background && localOut) {
    const harness = `
await (async function localHarness() {
  const ps = require('photoshop'); const lfs = require('uxp').storage.localFileSystem;
  const status = { phase: 'start' };
  async function writeOut(text) {
    const folder = await lfs.getEntryWithUrl(${JSON.stringify('file:' + dirname(localOut))});
    const f = await folder.createFile(${JSON.stringify(localOut.split('/').pop())}, { overwrite: true });
    await f.write(text);
  }
  try {
    await ps.core.executeAsModal(async () => {
      const entry = await lfs.getEntryWithUrl(${JSON.stringify('file:' + background)});
      const doc = await ps.app.open(entry);
      status.phase = 'opened';
      try {
        const result = await __colorDetection.run();
        status.phase = 'ran';
        await writeOut(JSON.stringify(result, null, 2));
      } finally {
        await doc.closeWithoutSaving();   // only the document this harness opened
      }
    }, { commandName: 'Territory Color Detection PoC' });
  } catch (e) {
    try { await writeOut(JSON.stringify({ ok: false, harnessError: String(e && e.message || e), status }, null, 2)); } catch (e2) {}
  }
})();
`
    writeFileSync(join(DIST, 'color-detection.local-test.psjs'), await bundle(harness, config))
  }
  const script = readFileSync(join(DIST, 'color-detection.psjs'), 'utf8')
  const request = {
    image: { source: { url: '<presigned URL of the background-only render>' } },
    options: {
      additionalContents: [{ source: { url: '<presigned URL of config.json: { textLayout, palette, options }>' } }],
      uxp: { source: { content: script, contentType: 'application/javascript' } },
    },
    outputs: [{ mediaType: 'application/json', destination: { validityPeriod: 3600 }, scriptOutputPattern: 'color-decision.json' }],
  }
  writeFileSync(join(DIST, 'execute-actions.request.json'), JSON.stringify(request, null, 2) + '\n')

  // --- "Photoshop action V2" node probe ---
  const probe = 'src/node-probe.js'
  writeFileSync(join(DIST, 'node-probe.psjs'), await bundle(run, null, probe))
  writeFileSync(join(DIST, 'node-probe.embedded.psjs'), await bundle(run, config, probe))
  writeFileSync(join(DIST, 'node-probe.embedded.noawait.psjs'), await bundle(runNoAwait, config, probe))
  // minimal smoke test (no bundling needed)
  const smoke = readFileSync(join(HERE, 'src/smoke.js'), 'utf8')
  if (!/\nawait main\(\)\s*$/.test(smoke)) throw new Error('smoke.js must end with "await main()"')
  writeFileSync(join(DIST, 'smoke.psjs'), smoke)
  writeFileSync(join(DIST, 'smoke.noawait.psjs'), smoke.replace(/\nawait main\(\)\s*$/, '\nmain()\n'))
  const probeDir = arg('--probe-dir', '')
  if (background && probeDir) {
    // simulate the node: the platform replaces __ADDITIONAL_CONTENTS_PATH_0__ with the Assets file
    const configPng = join(probeDir, 'config.png')
    const saveAs = {
      png: { _obj: 'PNGFormat', method: { _enum: 'PNGMethod', _value: 'quick' } },
      jpg: { _obj: 'JPEG', extendedQuality: 10, matteColor: { _enum: 'matteColor', _value: 'none' } },
      psd: { _obj: 'photoshop35Format', maximizeCompatibility: true },
      tif: { _obj: 'TIFF', byteOrder: { _enum: 'platform', _value: 'IBMPC' } },
    }
    const harness = `
await (async function probeHarness() {
  const ps = require('photoshop'); const uxp = require('uxp'); const lfs = uxp.storage.localFileSystem;
  const folder = await lfs.getEntryWithUrl(${JSON.stringify('file:' + probeDir)});
  async function writeText(name, text) { const f = await folder.createFile(name, { overwrite: true }); await f.write(text); }
  const saveAs = ${JSON.stringify(saveAs)};
  try {
    await ps.core.executeAsModal(async () => {
      const doc = await ps.app.open(await lfs.getEntryWithUrl(${JSON.stringify('file:' + background)}));
      try {
        const report = await __colorDetection.run();
        await writeText('probe-report.json', JSON.stringify(report, null, 2));
        const saved = {};
        for (const ext of Object.keys(saveAs)) {
          try {
            const f = await folder.createFile('processed.' + ext, { overwrite: true });
            await ps.app.batchPlay([{ _obj: 'save', as: saveAs[ext], in: { _path: lfs.createSessionToken(f), _kind: 'local' }, documentID: doc.id, copy: true, lowerCase: true }], { modalBehavior: 'execute' });
            saved[ext] = 'ok';
          } catch (e) { saved[ext] = String(e && e.message || e); }
        }
        await writeText('saved.json', JSON.stringify(saved));
      } finally {
        await doc.closeWithoutSaving();   // only the document this harness opened
      }
    }, { commandName: 'Territory Color Detection probe' });
  } catch (e) {
    try { await writeText('probe-report.json', JSON.stringify({ harnessError: String(e && e.message || e) })); } catch (e2) {}
  }
})();
`
    // smoke harness: smoke.js (top-level "await main()" replaced) run on the opened background
    const smokeHarness = smoke.replace(/\nawait main\(\)\s*$/, '\n') + `
await (async function smokeHarness() {
  const ps = require('photoshop'); const lfs = require('uxp').storage.localFileSystem;
  const folder = await lfs.getEntryWithUrl(${JSON.stringify('file:' + probeDir)});
  const saveAs = ${JSON.stringify(saveAs)};
  const status = {};
  try {
    await ps.core.executeAsModal(async () => {
      const doc = await ps.app.open(await lfs.getEntryWithUrl(${JSON.stringify('file:' + background)}));
      try {
        await main();
        status.main = 'done';
        for (const ext of ['psd', 'png', 'jpg']) {
          try {
            const f = await folder.createFile('smoke.' + ext, { overwrite: true });
            await ps.app.batchPlay([{ _obj: 'save', as: saveAs[ext], in: { _path: lfs.createSessionToken(f), _kind: 'local' }, documentID: doc.id, copy: true, lowerCase: true }], { modalBehavior: 'execute' });
            status[ext] = 'ok';
          } catch (e) { status[ext] = String(e && e.message || e); }
        }
      } finally {
        await doc.closeWithoutSaving();   // only the document this harness opened
      }
    }, { commandName: 'Territory smoke test' });
  } catch (e) { status.error = String(e && e.message || e); }
  const out = await folder.createFile('smoke-status.json', { overwrite: true });
  await out.write(JSON.stringify(status));
})();
`
    writeFileSync(join(DIST, 'smoke.local-test.psjs'), smokeHarness.split('__ADDITIONAL_CONTENTS_PATH_0__').join(configPng))
    const code = (await bundle(harness, null, probe)).split('__ADDITIONAL_CONTENTS_PATH_0__').join(configPng)
    writeFileSync(join(DIST, 'node-probe.local-test.psjs'), code)
  }
  // --- production: decision as XMP only (no visible change) ---
  // Errors from writing the decision propagate on purpose: the node run fails
  // rather than emitting an image without a decision.
  const production = await bundle('await __colorDetection.run();\n', null, 'src/production.js')
  writeFileSync(join(DIST, 'color-decision.psjs'), production)
  const variants = readdirSync(join(HERE, 'test-data')).map((f) => /^config\.(.+)\.json$/.exec(f)).filter(Boolean).map((m) => m[1]).filter((v) => v !== 'marderabwehr')
  for (const v of variants) writeFileSync(join(DIST, `config.${v}.png`), await makeConfigPng(readFileSync(join(HERE, 'test-data', `config.${v}.json`), 'utf8')))
  if (background && probeDir) {
    const saveAs = {
      png: { _obj: 'PNGFormat', method: { _enum: 'PNGMethod', _value: 'quick' } },
      jpg: { _obj: 'JPEG', extendedQuality: 10, matteColor: { _enum: 'matteColor', _value: 'none' } },
      psd: { _obj: 'photoshop35Format', maximizeCompatibility: true },
      tif: { _obj: 'TIFF', byteOrder: { _enum: 'platform', _value: 'IBMPC' } },
    }
    for (const v of variants) {
      const harness = `
await (async function productionHarness() {
  const ps = require('photoshop'); const lfs = require('uxp').storage.localFileSystem;
  const folder = await lfs.getEntryWithUrl(${JSON.stringify('file:' + probeDir)});
  const saveAs = ${JSON.stringify(saveAs)};
  const status = { variant: ${JSON.stringify(v)} };
  try {
    await ps.core.executeAsModal(async () => {
      const doc = await ps.app.open(await lfs.getEntryWithUrl(${JSON.stringify('file:' + background)}));
      try {
        try { status.decision = await __colorDetection.run(); } catch (e) { status.runError = String(e && e.message || e); }
        status.layers = doc.layers.length;
        status.size = [doc.width, doc.height];
        for (const ext of Object.keys(saveAs)) {
          try {
            const f = await folder.createFile(${JSON.stringify(v + '.')} + ext, { overwrite: true });
            await ps.app.batchPlay([{ _obj: 'save', as: saveAs[ext], in: { _path: lfs.createSessionToken(f), _kind: 'local' }, documentID: doc.id, copy: true, lowerCase: true }], { modalBehavior: 'execute' });
            status[ext] = 'ok';
          } catch (e) { status[ext] = String(e && e.message || e); }
        }
      } finally {
        await doc.closeWithoutSaving();   // only the document this harness opened
      }
    }, { commandName: 'Territory Color Decision (local)' });
  } catch (e) { status.harnessError = String(e && e.message || e); }
  const out = await folder.createFile(${JSON.stringify(v + '.status.json')}, { overwrite: true });
  await out.write(JSON.stringify(status, null, 2));
})();
`
      const code = (await bundle(harness, null, 'src/production.js')).split('__ADDITIONAL_CONTENTS_PATH_0__').join(join(DIST, `config.${v}.png`))
      writeFileSync(join(DIST, `color-decision.local-${v}.psjs`), code)
    }
  }
  return { scriptBytes: Buffer.byteLength(script) }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = await buildAll()
  console.log(`built dist/*.psjs (script ${r.scriptBytes} bytes)`)
}
