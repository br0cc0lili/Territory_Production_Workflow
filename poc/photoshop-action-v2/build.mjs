// Builds the Photoshop UXP scripts (single files — the execute-actions sandbox
// can only require photoshop / uxp / fs, so our code is bundled in):
//
//   dist/color-detection.psjs            config from additionalContents[0] (per run)
//   dist/color-detection.embedded.psjs   config embedded (test data) — for a node
//                                        that only takes a script
//   dist/color-detection.local-test.psjs desktop Photoshop harness: opens the test
//                                        background, runs, copies the JSON out,
//                                        closes ONLY that document
//   dist/execute-actions.request.json    example Photoshop API v2 request body (not sent)
//
//   node poc/photoshop-action-v2/build.mjs [--config <json>] [--background <png>] [--out <json>]
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const DIST = join(HERE, 'dist')
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d }
const configFile = resolve(arg('--config', join(HERE, 'test-data/config.marderabwehr.json')))
const background = arg('--background', '')
const localOut = arg('--out', '')

async function bundle(extraFooter = '', embedded = null) {
  const r = await build({
    entryPoints: [join(HERE, 'src/entry.js')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: '__colorDetection',
    platform: 'neutral',
    target: 'es2019',
    external: ['photoshop', 'uxp', 'fs'],
    mainFields: ['main'],
    legalComments: 'none',
  })
  let code = r.outputFiles[0].text
  if (embedded !== null) {
    const literal = JSON.stringify('@@EMBEDDED_CONFIG@@')
    if (!code.includes(literal)) throw new Error('embedded-config sentinel lost in bundle')
    code = code.replace(literal, JSON.stringify(JSON.stringify(JSON.parse(embedded))))
  }
  if (!code.includes('__ADDITIONAL_CONTENTS_PATH_0__')) throw new Error('placeholder lost in bundle')
  return `// Territory Color Detection — Photoshop UXP script (PoC). Generated by build.mjs; do not edit.\n${code}\n${extraFooter}`
}

export async function buildAll() {
  mkdirSync(DIST, { recursive: true })
  const config = readFileSync(configFile, 'utf8')
  JSON.parse(config)
  const run = 'Promise.resolve(__colorDetection.run()).catch(function (e) { console.error(e) });\n'
  writeFileSync(join(DIST, 'color-detection.psjs'), await bundle(run))
  writeFileSync(join(DIST, 'color-detection.embedded.psjs'), await bundle(run, config))
  if (background && localOut) {
    const harness = `
(async function localHarness() {
  const ps = require('photoshop'); const lfs = require('uxp').storage.localFileSystem;
  const status = { phase: 'start' };
  async function writeOut(text) {
    const folder = await lfs.getEntryWithUrl(${JSON.stringify('file:' + dirname(localOut))});
    const f = await folder.createFile(${JSON.stringify(localOut.split('/').pop())}, { overwrite: true });
    await f.write(text);
  }
  try {
    await ps.core.executeAsModal(async () => {
      const entry = await lfs.getEntryWithUrl(${JSON.stringify('file:' + background)});
      const doc = await ps.app.open(entry);
      status.phase = 'opened';
      try {
        const result = await __colorDetection.run();
        status.phase = 'ran';
        await writeOut(JSON.stringify(result, null, 2));
      } finally {
        await doc.closeWithoutSaving();   // only the document this harness opened
      }
    }, { commandName: 'Territory Color Detection PoC' });
  } catch (e) {
    try { await writeOut(JSON.stringify({ ok: false, harnessError: String(e && e.message || e), status }, null, 2)); } catch (e2) {}
  }
})();
`
    writeFileSync(join(DIST, 'color-detection.local-test.psjs'), await bundle(harness, config))
  }
  const script = readFileSync(join(DIST, 'color-detection.psjs'), 'utf8')
  const request = {
    image: { source: { url: '<presigned URL of the background-only render>' } },
    options: {
      additionalContents: [{ source: { url: '<presigned URL of config.json: { textLayout, palette, options }>' } }],
      uxp: { source: { content: script, contentType: 'application/javascript' } },
    },
    outputs: [{ mediaType: 'application/json', destination: { validityPeriod: 3600 }, scriptOutputPattern: 'color-decision.json' }],
  }
  writeFileSync(join(DIST, 'execute-actions.request.json'), JSON.stringify(request, null, 2) + '\n')
  return { scriptBytes: Buffer.byteLength(script) }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = await buildAll()
  console.log(`built dist/*.psjs (script ${r.scriptBytes} bytes)`)
}
