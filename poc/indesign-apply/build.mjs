// Builds the InDesign side of the Color Decision hand-over:
//
//   dist/capability/manifest.json + apply-color-decision.idjs
//   dist/apply-color-decision.zip      InDesign API Custom Scripts bundle (NOT registered)
//   dist/apply-color-decision.local-test.idjs   desktop InDesign harness (with --images/--report):
//       creates a NEW scratch document (one page per image: "<<Headline>>" text frame +
//       "<<MainImage>>" with the processed image placed), applies, reads the result
//       back and closes ONLY that document without saving.
//
//   node poc/indesign-apply/build.mjs [--images a.png,b.png,…] [--report <dir>]
import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const DIST = join(HERE, 'dist')
const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d }

export const MANIFEST = {
  manifestVersion: '1.0.0',
  name: 'territory-apply-color-decision',
  version: '0.1.0',
  host: { app: 'indesign', minVersion: '18.4.0', maxVersion: '99.9.9' },
  apiEntryPoints: [{ type: 'capability', path: 'apply-color-decision.idjs', language: 'uxpscript' }],
}

async function bundle(footer) {
  const r = await build({
    entryPoints: [join(HERE, 'src/capability.js')], bundle: true, write: false, format: 'iife', globalName: '__applyColorDecision',
    platform: 'neutral', target: 'es2019', external: ['indesign', 'uxp'], mainFields: ['main'], legalComments: 'none',
  })
  return `// Territory — apply Color Decision (InDesign UXP). Generated by build.mjs; do not edit.\n${r.outputFiles[0].text}\n${footer}`
}

export async function buildAll({ images = [], reportDir = '' } = {}) {
  rmSync(join(DIST, 'capability'), { recursive: true, force: true })
  mkdirSync(join(DIST, 'capability'), { recursive: true })
  const entry = await bundle(`
try {
  const out = await __applyColorDecision.main();
  require('uxp').script.setResult(JSON.stringify(out));
} catch (e) {
  require('uxp').script.setResult(JSON.stringify({ status: 'FAILURE', errorCode: 'internal_error', errorString: String((e && e.message) || e) }));
}
`)
  writeFileSync(join(DIST, 'capability/apply-color-decision.idjs'), entry)
  writeFileSync(join(DIST, 'capability/manifest.json'), JSON.stringify(MANIFEST, null, 2) + '\n')
  rmSync(join(DIST, 'apply-color-decision.zip'), { force: true })
  try { execFileSync('zip', ['-q', '-j', join(DIST, 'apply-color-decision.zip'), join(DIST, 'capability/manifest.json'), join(DIST, 'capability/apply-color-decision.idjs')]) } catch (e) { /* zip CLI missing — the folder is the bundle */ }

  if (images.length && reportDir) {
    const harness = `
await (async function localApplyTest() {
  const idm = require('indesign'); const app = idm.app; const uxp = require('uxp');
  const images = ${JSON.stringify(images)};
  const report = { before: app.documents.length, pages: [] };
  let doc = null;
  try {
    doc = app.documents.add(false); // new scratch document, no window
    report.created = true;
    // new documents default to mm — work in points on a 1080 × 1080 pt page
    doc.viewPreferences.horizontalMeasurementUnits = idm.MeasurementUnits.POINTS;
    doc.viewPreferences.verticalMeasurementUnits = idm.MeasurementUnits.POINTS;
    doc.documentPreferences.facingPages = false;
    doc.documentPreferences.pageWidth = 1080;
    doc.documentPreferences.pageHeight = 1080;
    while (doc.pages.length < images.length) doc.pages.add();
    for (let i = 0; i < images.length; i++) {
      const page = doc.pages.item(i);
      // UXP DOM: add() ignores a properties object — set them afterwards
      const rect = page.rectangles.add();
      rect.geometricBounds = [0, 0, 1080, 1080];
      rect.name = '<<MainImage>>';
      rect.place(images[i]);
      const tf = page.textFrames.add();
      tf.geometricBounds = [80, 60, 300, 700];
      tf.contents = 'Marderabwehr headline\\rSubline text';
      tf.name = '<<Headline>>';
    }
    const res = await __applyColorDecision.applyToDocument(doc, idm, {}, '/');
    report.result = res;
    for (let i = 0; i < images.length; i++) {
      const page = doc.pages.item(i);
      const frame = __applyColorDecision.findNamed(page, '<<Headline>>', true);
      const paras = frame.parentStory.paragraphs;
      const fills = [];
      for (let k = 0; k < paras.length; k++) { const c = paras.item(k).fillColor; fills.push({ name: String(c.name), space: String(c.space), value: Array.from(c.colorValue || []) }); }
      report.pages.push({ image: images[i].split('/').pop(), fills, label: frame.extractLabel('posterBatch.textColor') });
    }
  } catch (e) {
    report.error = String((e && e.message) || e);
  } finally {
    if (doc && doc.isValid) { try { doc.close(idm.SaveOptions.NO); report.closed = true; } catch (e) { report.closeError = String(e && e.message || e); } }
    report.after = app.documents.length;
  }
  const folder = await uxp.storage.localFileSystem.getEntryWithUrl(${JSON.stringify('file:' + reportDir)});
  const f = await folder.createFile('indesign-apply-report.json', { overwrite: true });
  await f.write(JSON.stringify(report, null, 2));
})();
`
    writeFileSync(join(DIST, 'apply-color-decision.local-test.idjs'), await bundle(harness))
  }
  return { bytes: Buffer.byteLength(entry) }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const images = (arg('--images', '') || '').split(',').filter(Boolean).map((p) => resolve(p))
  const r = await buildAll({ images, reportDir: arg('--report', '') && resolve(arg('--report', '')) })
  console.log(`built dist/capability (${r.bytes} bytes)${images.length ? ' + local test' : ''}`)
}
